import assert from 'node:assert/strict';
import {keyName,chordFor,attachRecorder} from '../companion/postcard/shortcut-recorder.js';
assert.equal(chordFor(['ControlLeft','ShiftLeft','KeyA']),'Ctrl+Shift+A');
assert.equal(chordFor(['AltLeft','AltRight']),'LeftAlt+RightAlt');
assert.equal(chordFor(['Space']),'Space');
assert.equal(chordFor(['NumpadAdd']),'NumpadAdd');
assert.equal(keyName('Digit5'),'5');
assert.equal(chordFor(['KeyA','KeyB']),null);
assert.equal(chordFor(['Unidentified']),null);
