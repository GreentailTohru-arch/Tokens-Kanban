attachRecorder(input,v=>changes.push(v),()=>{});
const event=(code,extra={})=>({code,preventDefault(){},stopPropagation(){},...extra});
handlers.keydown(event('ControlLeft',{ctrlKey:true}));
handlers.keydown(event('KeyC',{ctrlKey:true}));
handlers.keyup(event('KeyC',{ctrlKey:true}));
handlers.keyup(event('ControlLeft'));
