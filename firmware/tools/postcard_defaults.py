"""Bake the production browser's default postcard into flash-only RGB565 data.

Requires playwright, and an installed Chromium browser with Microsoft YaHei UI
for matching the Windows reference. Does not connect to or write any device.
"""
from pathlib import Path
from http.server import ThreadingHTTPServer
import argparse
import sys
import threading
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'companion'))
from postcard_server import Handler


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--browser', required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    server = ThreadingHTTPServer(('127.0.0.1', 0), Handler)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    try:
        with sync_playwright() as p:
            browser = p.chromium.launch(executable_path=args.browser, headless=True)
            page = browser.new_page()
            page.goto(f'http://127.0.0.1:{server.server_port}/')
            data = bytes(page.evaluate('''async()=>{
                const {loadDefaults}=await import('./defaults.js');
                const {renderFace,FACE_BYTES}=await import('./codec.js');
                const content=await loadDefaults(),canvas=document.createElement('canvas');
                canvas.width=240;canvas.height=264;
                const result=new Uint8Array(FACE_BYTES*2);
                result.set(renderFace(canvas,content,false));
                result.set(renderFace(canvas,content,true),FACE_BYTES);
                content.photo.close();content.qr.close();return Array.from(result);
            }'''))
            browser.close()
        assert len(data) == 253440
        code = '/* Generated by tools/postcard_defaults.py. Flash-only default postcard. */\n'
        code += '#include "postcard_defaults.h"\nconst uint8_t postcard_default_pixels[POSTCARD_BYTES]={\n'
        code += '\n'.join('    ' + ','.join(f'0x{x:02x}' for x in data[i:i+32]) + ','
                          for i in range(0, len(data), 32)) + '\n};\n'
        path = ROOT / 'assets/images/postcard_default_rgb565.c'
        if args.check:
            assert path.read_text(encoding='utf-8') == code, 'Stale default postcard'
        else:
            path.write_text(code, encoding='utf-8')
        print('Default postcard browser/RGB565 identity: PASS')
    finally:
        server.shutdown()


if __name__ == '__main__':
    main()
