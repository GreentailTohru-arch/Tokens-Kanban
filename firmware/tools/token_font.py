"""Generate and verify the fixed UI's Noto CJK 14px LVGL PLAIN 4bpp subset."""
from pathlib import Path
import argparse
import hashlib
import json
import re
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

ROOT=Path(__file__).resolve().parents[1]
ASSETS=ROOT/'assets/fonts'
def build():
    source=ASSETS/'NotoSansCJKsc-Regular.otf'
    font=ImageFont.truetype(str(source),14)
    coverage=TTFont(source).getBestCmap()
    strings=re.findall(r'"([^"\n]*)"',(ROOT/'main/token_ui.c').read_text(encoding='utf-8'))
    chars=sorted(set(range(32,127))|{ord(c) for s in strings for c in s if ord(c)>127})
    assert all(c in coverage for c in chars), 'Source font missing glyph'
    assert 0x9F98 not in chars, 'Negative coverage control unexpectedly included'
    bitmap=[]; descriptors=['    {0},']; expected=[]
    for cp in chars:
        ch=chr(cp); left,top,right,bottom=font.getbbox(ch,anchor='ls')
        width,height=right-left,bottom-top
        image=Image.new('L',(max(1,width),max(1,height)))
        ImageDraw.Draw(image).text((-left,-top),ch,font=font,fill=255,anchor='ls')
        pixels=[(p+8)//17 for p in image.getdata()] if width*height else []
        offset=len(bitmap)
        for i in range(0,len(pixels),2): bitmap.append((pixels[i]<<4)|(pixels[i+1] if i+1<len(pixels) else 0))
        descriptors.append(f'    {{.bitmap_index={offset},.adv_w={round(font.getlength(ch)*16)},.box_w={width},.box_h={height},.ofs_x={left},.ofs_y={-bottom}}},')
        expected.append((offset,pixels))
    extras=[c for c in chars if c>126]; start=extras[0]
    code='/* Generated by tools/token_font.py; Noto Sans CJK SC, SIL OFL. */\n#include "lvgl.h"\n'
    code+='static const uint8_t glyph_bitmap[]={\n'+ '\n'.join('    '+','.join(f'0x{x:02x}' for x in bitmap[i:i+24])+',' for i in range(0,len(bitmap),24))+'\n};\n'
    code+='static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[]={\n'+'\n'.join(descriptors)+'\n};\n'
    code+='static const uint16_t unicode_list[]={'+','.join(str(c-start) for c in extras)+'};\n'
    code+='static const lv_font_fmt_txt_cmap_t cmaps[]={\n'
    code+=' {.range_start=32,.range_length=95,.glyph_id_start=1,.type=LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},\n'
    code+=f' {{.range_start={start},.range_length={extras[-1]-start+1},.glyph_id_start=96,.unicode_list=unicode_list,.list_length={len(extras)},.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}\n}};\n'
    code+='static lv_font_fmt_txt_dsc_t font_dsc={.glyph_bitmap=glyph_bitmap,.glyph_dsc=glyph_dsc,.cmaps=cmaps,.cmap_num=2,.bpp=4,.bitmap_format=0};\n'
    code+='const lv_font_t token_font_14={.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height=18,.base_line=4,.dsc=&font_dsc};\n'
    # Reparse the actual serialized bytes and verify every pixel before accepting output.
    serialized=bytes(int(x,16) for x in re.findall(r'0x([0-9a-f]{2})',code.split('};',1)[0]))
    for offset,pixels in expected:
        decoded=[(serialized[offset+i//2]>>(4 if i%2==0 else 0))&15 for i in range(len(pixels))]
        assert decoded==pixels
    inventory=json.dumps({'fontSha256':hashlib.sha256(source.read_bytes()).hexdigest(),'size':14,'lineHeight':18,'codepoints':chars,'bitmapBytes':len(bitmap)},indent=2)+'\n'
    return code,inventory
def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    code,inventory=build()
    for name,content in [('token_font_14.c',code),('token_font_inventory.json',inventory)]:
        path=ASSETS/name
        if args.check: assert path.read_text(encoding='utf-8')==content, f'Stale {name}'
        else: path.write_text(content,encoding='utf-8')
    print('Font coverage and bitmap round-trip: PASS')
if __name__=='__main__':main()
