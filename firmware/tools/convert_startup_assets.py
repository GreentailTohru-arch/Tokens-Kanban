"""Adapt the supplied logo and startup recording; never regenerate the artwork."""
from pathlib import Path
import argparse,hashlib,io,json,struct,subprocess,wave
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
LOGO=ROOT/'assets/images/startup-logo.png'
SOUND=ROOT/'assets/music/macos-startup.mp3'
WAV=ROOT/'assets/music/startup.wav'
BINDING=ROOT/'assets/music/startup_decode.json'
def sha(data):return hashlib.sha256(data).hexdigest()
def decode(ffmpeg,check):
    raw=subprocess.run([ffmpeg,'-nostdin','-v','error','-i',str(SOUND),'-map','0:a:0',
        '-ac','1','-ar','16000','-c:a','pcm_s16le','-f','s16le','-'],check=True,capture_output=True).stdout
    output=io.BytesIO()
    with wave.open(output,'wb') as f:f.setnchannels(1);f.setsampwidth(2);f.setframerate(16000);f.writeframes(raw)
    data=output.getvalue()
    binding=json.dumps({'source_sha256':sha(SOUND.read_bytes()),'wav_sha256':sha(data)},indent=2)+'\n'
    if check:
        assert WAV.read_bytes()==data and BINDING.read_text(encoding='utf-8')==binding,'Stale startup decode cache'
    else:
        WAV.write_bytes(data);BINDING.write_text(binding,encoding='utf-8')
def generate():
    binding=json.loads(BINDING.read_text(encoding='utf-8'))
    assert binding=={'source_sha256':sha(SOUND.read_bytes()),'wav_sha256':sha(WAV.read_bytes())},'Run --decode --ffmpeg <path>'
    image=Image.open(LOGO).convert('RGBA')
    black=Image.new('RGBA',image.size,(0,0,0,255));black.alpha_composite(image)
    visible=black.convert('RGB');bounds=visible.getbbox();assert bounds,'Logo is blank'
    mark=visible.crop(bounds);mark.thumbnail((88,110),Image.Resampling.LANCZOS)
    canvas=Image.new('RGB',(240,320));position=((240-mark.width)//2,(320-mark.height)//2)
    canvas.paste(mark,position)
    rgb565=bytearray()
    for r,g,b in canvas.getdata():rgb565.extend(struct.pack('<H',((r>>3)<<11)|((g>>2)<<5)|(b>>3)))
    with wave.open(str(WAV),'rb') as f:
        assert (f.getnchannels(),f.getsampwidth(),f.getframerate())==(1,2,16000)
        pcm=f.readframes(f.getnframes())
    assert 0<len(pcm)<=16000*2*5,'Startup must fit the bounded five-second presentation'
    samples=struct.unpack('<'+'h'*(len(pcm)//2),pcm)
    lines=['/* Generated by tools/convert_startup_assets.py from supplied files. */','#include "startup_assets.h"','',
           'const uint8_t startup_logo_rgb565[STARTUP_WIDTH*STARTUP_HEIGHT*2] = {']
    lines.extend('    '+','.join(map(str,rgb565[i:i+24]))+',' for i in range(0,len(rgb565),24))
    lines.extend(['};','','const int16_t startup_sound_pcm[] = {'])
    lines.extend('    '+','.join(map(str,samples[i:i+16]))+',' for i in range(0,len(samples),16))
    lines.extend(['};','const size_t startup_sound_samples = sizeof(startup_sound_pcm)/sizeof(startup_sound_pcm[0]);',''])
    info={'logo_source_sha256':sha(LOGO.read_bytes()),'logo_source_size':list(image.size),'visible_source_bounds':list(bounds),
          'logo_size':list(mark.size),'logo_position':list(position),'canvas':[240,320],'rgb565_sha256':sha(rgb565),
          'audio_source_sha256':sha(SOUND.read_bytes()),'wav_sha256':sha(WAV.read_bytes()),'rate':16000,
          'samples':len(samples),'seconds':len(samples)/16000,'pcm_sha256':sha(pcm),'peak':max(map(abs,samples))}
    # Preview the quantized pixels actually embedded in the firmware.
    pixels=[]
    for (c,) in struct.iter_unpack('<H',rgb565):pixels.append((((c>>11)&31)*255//31,((c>>5)&63)*255//63,(c&31)*255//31))
    preview=Image.new('RGB',(240,320));preview.putdata(pixels);output=io.BytesIO();preview.save(output,format='PNG')
    return {'assets/images/startup_assets.c':'\n'.join(lines).encode(),
            'assets/images/startup_assets.json':(json.dumps(info,indent=2)+'\n').encode(),
            'assets/images/startup-preview.png':output.getvalue()}
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');p.add_argument('--decode',action='store_true');p.add_argument('--ffmpeg');args=p.parse_args()
    if args.decode:
        if not args.ffmpeg:p.error('--decode requires --ffmpeg')
        decode(args.ffmpeg,args.check)
    for name,data in generate().items():
        path=ROOT/name
        if args.check:assert path.read_bytes()==data,'Outdated startup asset: '+name
        else:path.write_bytes(data)
    print('Supplied startup logo and recording, decode binding and RGB565 preview: PASS')
if __name__=='__main__':main()
