"""Convert supplied Codex/OpenCode/Antigravity recordings to flash-only PCM.

Uses a normalized 97-tap Hann-windowed sinc low-pass before decimation. No gain,
normalization, trimming or playback-speed changes. Python standard library only.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import struct
import subprocess
import wave

ROOT=Path(__file__).resolve().parents[1]
ASSETS=ROOT/'assets/music'
COMPRESSED={('opencode','complete'):'opencode-complete.aac',('opencode','error'):'opencode-error.aac',
    ('antigravity','complete'):'antigravityCascadeDone.mp3',('antigravity','error'):'antigravityActionRequired.mp3'}

def read_mono(path):
    with wave.open(str(path),'rb') as f:
        channels,width,rate,frames=f.getnchannels(),f.getsampwidth(),f.getframerate(),f.getnframes()
        if f.getcomptype()!='NONE' or channels not in (1,2) or width not in (2,3) or rate not in (16000,48000):
            raise ValueError('Expected 16/48kHz, 16/24-bit mono/stereo PCM WAV')
        data=f.readframes(frames)
    if len(data)!=frames*channels*width:raise ValueError('Truncated WAV')
    samples=[]
    for offset in range(0,len(data),channels*width):
        value=sum(int.from_bytes(data[offset+c*width:offset+(c+1)*width],'little',signed=True) for c in range(channels))/channels
        samples.append(value/(1<<(width*8-16)))
    return samples,dict(channels=channels,bits=width*8,rate=rate,frames=frames,seconds=frames/rate)

def decimate(samples,rate=48000):
    if rate==16000:return [max(-32768,min(32767,round(v))) for v in samples]
    if rate!=48000:raise ValueError('Unsupported source rate')
    radius=48;cutoff=.15  # 7.2kHz cutoff, below the 8kHz output Nyquist limit.
    kernel=[(2*cutoff if d==0 else math.sin(2*math.pi*cutoff*d)/(math.pi*d))*(.5+.5*math.cos(math.pi*d/radius)) for d in range(-radius,radius+1)]
    total=sum(kernel);kernel=[k/total for k in kernel]
    out=[]
    for center in range(0,len(samples),3):
        value=sum(k*samples[center+d] for d,k in zip(range(-radius,radius+1),kernel) if 0<=center+d<len(samples))
        out.append(max(-32768,min(32767,round(value))))
    return out

def digest(path):return hashlib.sha256(path.read_bytes()).hexdigest()

def decode_sources(ffmpeg,check=False):
    """Decode only on the host, honoring each format's standard padding metadata."""
    receipt={}
    for (bank,event),filename in COMPRESSED.items():
        source=ASSETS/filename;target=ASSETS/f'{bank}-{event}.wav'
        raw=subprocess.run([ffmpeg,'-nostdin','-v','error','-i',str(source),'-map','0:a:0',
            '-ac','1','-ar','16000','-c:a','pcm_s16le','-f','s16le','-'],capture_output=True,check=True).stdout
        import io
        stream=io.BytesIO()
        with wave.open(stream,'wb') as f:f.setnchannels(1);f.setsampwidth(2);f.setframerate(16000);f.writeframes(raw)
        data=stream.getvalue()
        if check:
            if target.read_bytes()!=data:raise ValueError('Decode cache differs: '+target.name)
        else:target.write_bytes(data)
        receipt[source.name]={'source_sha256':digest(source),'decoded_sha256':hashlib.sha256(data).hexdigest()}
    text=json.dumps(receipt,indent=2)+'\n';path=ASSETS/'recording_decode.json'
    if check:
        if path.read_text(encoding='utf-8')!=text:raise ValueError('Decode receipt differs')
    else:path.write_text(text,encoding='utf-8')

def generate():
    lines=['/* Generated by tools/convert_codex_sounds.py; user-supplied audio. */','#include "device_sounds.h"','']
    inventory={}
    receipt=json.loads((ASSETS/'recording_decode.json').read_text(encoding='utf-8'))
    for bank,name in (('codex','notification'),('codex','error'),*COMPRESSED):
        path=ASSETS/f'{bank}-{name}.wav';samples,info=read_mono(path);pcm=decimate(samples,info['rate'])
        source=path
        if (bank,name) in COMPRESSED:
            source=ASSETS/COMPRESSED[(bank,name)];binding=receipt[source.name]
            if binding!={'source_sha256':digest(source),'decoded_sha256':digest(path)}:
                raise ValueError('Stale decode cache; run with --decode --ffmpeg <path>')
        symbol=f'{bank}_{name}'
        lines.append(f'const int16_t {symbol}_pcm[] = {{')
        lines.extend('    '+','.join(map(str,pcm[i:i+16]))+',' for i in range(0,len(pcm),16))
        lines.extend(['};',f'const size_t {symbol}_samples = sizeof({symbol}_pcm)/sizeof({symbol}_pcm[0]);',''])
        raw=struct.pack('<'+'h'*len(pcm),*pcm)
        inventory[source.name]={**info,'source_sha256':digest(source),'decoded_wav':path.name,'decoded_sha256':digest(path),'output_rate':16000,'output_samples':len(pcm),'pcm_sha256':hashlib.sha256(raw).hexdigest(),'peak':max(map(abs,pcm))}
    return '\n'.join(lines),json.dumps(inventory,indent=2)+'\n'

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');parser.add_argument('--decode','--decode-aac',dest='decode',action='store_true');parser.add_argument('--ffmpeg');args=parser.parse_args()
    if args.decode:
        if not args.ffmpeg:parser.error('--decode requires --ffmpeg')
        decode_sources(args.ffmpeg,args.check)
    source,inventory=generate()
    for path,text in [(ASSETS/'codex_sounds.c',source),(ASSETS/'codex_sounds.json',inventory)]:
        if args.check:
            if path.read_text(encoding='utf-8')!=text:raise SystemExit(f'Outdated asset: {path}')
        else:path.write_text(text,encoding='utf-8')
    print('Supplied Codex/OpenCode/Antigravity recordings -> 16kHz mono flash assets: PASS')

if __name__=='__main__':main()
